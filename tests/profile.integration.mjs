import test from 'node:test';
import assert from 'node:assert/strict';
const base = process.env.TEST_BASE_URL;
if (!base) throw new Error('TEST_BASE_URL debe apuntar a un entorno aislado');

test('el perfil requiere sesión verificable y permite actualizar solo datos propios', async () => {
  const forged = await fetch(`${base}/api/profile`, { headers: { cookie: 'session_user=%7B%22id%22%3A%22000000000000000000000000%22%7D' } });
  assert.equal(forged.status, 401);
  const login = await fetch(`${base}/api/auth/login`, { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ username: 'admin', password: 'test-only-password' }) });
  assert.equal(login.status, 200);
  const cookies = login.headers.getSetCookie().map((c) => c.split(';')[0]).join('; ');
  const profile = await fetch(`${base}/api/profile`, { headers: { cookie: cookies } });
  assert.equal(profile.status, 200);
  const before = await profile.json();
  const update = await fetch(`${base}/api/profile`, { method: 'PATCH', headers: { cookie: cookies, 'content-type': 'application/json' }, body: JSON.stringify({ name: 'Perfil', surname: 'Prueba', email: before.email, role: 'owner' }) });
  assert.equal(update.status, 200);
  const after = await (await fetch(`${base}/api/profile`, { headers: { cookie: cookies } })).json();
  assert.equal(after.name, 'Perfil');
  assert.equal(after.role, before.role);
  const invalid = new FormData(); invalid.set('file', new Blob(['not image'], {type:'text/plain'}), 'test.txt');
  const bad = await fetch(`${base}/api/profile/avatar`, { method:'POST', headers:{cookie:cookies}, body:invalid });
  assert.equal(bad.status, 400);
  const photo = new FormData();
  photo.set('file', new Blob([Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+/aV0AAAAASUVORK5CYII=', 'base64')], {type:'image/png'}), 'avatar.png');
  const uploaded = await fetch(`${base}/api/profile/avatar`, { method:'POST', headers:{cookie:cookies}, body:photo });
  assert.equal(uploaded.status, 200);
  const {avatar} = await uploaded.json();
  assert.match(avatar, /^\/api\/uploads\//);
  assert.equal((await fetch(`${base}${avatar}`)).status, 200);
  const final = await (await fetch(`${base}/api/profile`, {headers:{cookie:cookies}})).json();
  assert.equal(final.avatar, avatar);
  assert.equal('password' in final, false);
  const gmLogin = await fetch(`${base}/api/auth/login`, { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ username: 'gm', password: 'test-only-password' }) });
  assert.equal(gmLogin.status, 200);
  const gmToken = gmLogin.headers.getSetCookie().find((c) => c.startsWith('profile_session=')).split(';')[0];
  const forgedAdmin = cookies.split('; ').find((c) => c.startsWith('session_user='));
  const gmProfile = await (await fetch(`${base}/api/profile`, { headers: { cookie: `${gmToken}; ${forgedAdmin}` } })).json();
  assert.equal(gmProfile.role, 'game_master');
  assert.notEqual(gmProfile.email, final.email);
  await fetch(`${base}/api/auth/logout`, { method:'POST', headers:{cookie:cookies} });
  assert.equal((await fetch(`${base}/api/profile`, {headers:{cookie:cookies}})).status, 401);
});
